/* plate v3: the PLT_OPTS block of deck/src/10-d4-plate.js (slide pltOptions) from options/{A,B,C,D}.json, the four directions
   sized by final.js (options/*.json 'how' says with what). Each: Theseus and the grid at the same weight (lens, front skate,
   back skate, twist, peak), the thinnest walls, and the drawing (twin walls expanded as gen_deck_data.js does; 'tall' marks
   option D's 3.9 mm tail struts).      node gen_options.js        (from this folder; writes into the deck file) */
const fs = require('fs'), path = require('path');
const DST = path.join(__dirname, '..', '..', '..', '..', 'deck', 'src', '10-d4-plate.js');
const r2 = v => Math.round(v * 100) / 100;
function twinExpand(nodes, mems, isTwin, gap = 0.8) {
  const N = nodes.map(p => p.slice()), acc = new Map(), plan = [];
  for (const m of mems) {
    if (!isTwin(m)) { plan.push([m]); continue; }
    const a = nodes[m[0]], b = nodes[m[1]], L = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1e-9;
    let n = [-(b[1] - a[1]) / L, (b[0] - a[0]) / L]; if (n[0] * (a[0] + b[0]) + n[1] * (a[1] + b[1]) < 0) n = [-n[0], -n[1]];
    const dd = m[3] / 4 + gap / 2, ends = [];
    for (const sg of [1, -1]) for (const k of [m[0], m[1]]) { const key = k + ':' + sg + ':' + m[2]; const q = acc.get(key) || [0, 0, 0]; q[0] += nodes[k][0] + sg * n[0] * dd; q[1] += nodes[k][1] + sg * n[1] * dd; q[2]++; acc.set(key, q); ends.push(key); }
    plan.push([m, ends]);
  }
  const id = new Map(); for (const [key, q] of acc) { id.set(key, N.length); N.push([q[0] / q[2], q[1] / q[2]]); }
  const out = [];
  for (const [m, ends] of plan) {
    if (!ends) { out.push(m); continue; }
    const h = m.slice(); h[3] = m[3] / 2; out.push(Object.assign(h.slice(), { 0: id.get(ends[0]), 1: id.get(ends[1]) }), Object.assign(h.slice(), { 0: id.get(ends[2]), 1: id.get(ends[3]) }));
  }
  return { nodes: N, mems: out };
}
const OPTS = {};
for (const X of ['A', 'B', 'C', 'D']) {
  const J = JSON.parse(fs.readFileSync(path.join(__dirname, 'options', X + '.json'))), fe = J.fe, TW = fe.twin, WC = fe.wcap;
  const isT = m => TW.includes(m[2]) && m[3] > WC + 1e-9;
  const walls = { lattice: 9, struts: 9, twin: 9 };
  for (const m of J.frame.members) { const w = isT(m) ? m[3] / 2 : m[3], k = m[2] === 'fine' ? 'lattice' : isT(m) ? 'twin' : 'struts'; walls[k] = Math.min(walls[k], w); }
  const e = twinExpand(J.frame.nodes, J.frame.members, isT);
  const pick = R => ({ lens: R.lens_um, pill: R.pill_um, back: R.back_um, twist: R.twist_um, max: R.max });
  OPTS[X] = { theseus: pick(fe.theseus), grid: pick(fe.grid), mass: fe.mass, walls: Object.fromEntries(Object.entries(walls).map(([k, v]) => [k, v < 9 ? r2(v) : null])),
    tallH: Math.max(...J.frame.members.map(m => m[4] || 2.3)), nodes: e.nodes.map(p => [r2(p[0]), r2(p[1])]), members: e.mems.map(m => [m[0], m[1], m[2] === 'fine' ? 0 : m[2] === 'ring' ? 2 : 1, r2(m[3] * 0.82), (m[4] || 2.3) > 2.31 ? 1 : 0]) };
}
const block = '/* ---- options, generated by gen_options.js from 3d/shell/tools/plate_fe/options (do not edit by hand) ---- */\nconst PLT_OPTS = ' + JSON.stringify(OPTS) + ';\n/* ---- end of options ---- */\n';
let src = fs.readFileSync(DST, 'utf8');
const a = src.indexOf('/* ---- options, generated by gen_options.js'), b0 = '/* ---- end of options ---- */\n';
if (a >= 0) src = src.slice(0, a) + block + src.slice(src.indexOf(b0) + b0.length);
else { const k = src.indexOf('/* ---- end of data ---- */\n') + '/* ---- end of data ---- */\n'.length; src = src.slice(0, k) + block + src.slice(k); }
fs.writeFileSync(DST + '.tmp', src); fs.renameSync(DST + '.tmp', DST);
console.log('PLT_OPTS', (block.length / 1024).toFixed(0), 'KB:', Object.entries(OPTS).map(([k, o]) => k + ' lens ' + o.theseus.lens + '/' + o.grid.lens + ' back ' + o.theseus.back + '/' + o.grid.back + ' walls ' + JSON.stringify(o.walls)).join(' | '));
