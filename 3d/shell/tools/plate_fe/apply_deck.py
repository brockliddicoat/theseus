#!/usr/bin/env python3
"""Paste deck_data.js (gen_deck_data.js) into deck/src/10-d4-plate.js between its data markers (plate v3).
    python3 -I apply_deck.py        (from this folder)"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
DST = os.path.join(HERE, '..', '..', '..', '..', 'deck', 'src', '10-d4-plate.js')
block = open(os.path.join(HERE, 'deck_data.js')).read()
src = open(DST).read()
a = src.index('/* ---- data, generated by the plate builder'); b = src.index('/* ---- end of data ---- */') + len('/* ---- end of data ---- */\n')
out = src[:a] + block + src[b:]
tmp = DST + '.tmp'; open(tmp, 'w').write(out); os.replace(tmp, DST)
print('pasted', len(block) // 1024, 'KB into', os.path.normpath(DST))
