#!/usr/bin/env python3
"""Offline CSG for the Theseus small parts (manifold3d), baked into ES modules under parts/geo/.

Only parts that genuinely need booleans live here (GT01 cover with windows and raised marking,
encoder housing, screw head recess, JST housings). Everything parametric stays procedural in JS.

Frames: meshes are written in the part's own JS frame (mm, +Y up). Internally manifold works Z-up;
`to_three` maps manifold (X, Y, Z) -> three (X, Z, -Y), a proper rotation (winding preserved).

Usage:  python3 -I parts/tools/build_geo.py            (writes parts/geo/*.geo.js)
"""
import base64, json, math, os, sys
import numpy as np
import manifold3d as m3
from manifold3d import Manifold, CrossSection, JoinType, FillRule

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, '..', 'geo'))
os.makedirs(OUT, exist_ok=True)
m3.set_circular_segments(48)

# ----------------------------------------------------------------------------- helpers
def rrect(w, h, r, cx=0.0, cy=0.0):
    """Rounded rectangle CrossSection (w along X, h along Y)."""
    r = min(r, w / 2 - 1e-4, h / 2 - 1e-4)
    cs = CrossSection.square([w, h], center=True)
    if r > 0:
        cs = cs.offset(-r, JoinType.Round).offset(r, JoinType.Round, circular_segments=48)
    return cs.translate([cx, cy])

def slab(cs, z0, z1):
    return cs.extrude(z1 - z0).translate([0, 0, z0])

def rounded_slab(cs, z0, z1, r, segs=32):
    """Prism with ALL convex edges rounded by r (minkowski with a sphere)."""
    core = cs.offset(-r, JoinType.Round).extrude(z1 - z0 - 2 * r).translate([0, 0, z0 + r])
    return Manifold.minkowski_sum(core, Manifold.sphere(r, segs))

def chamfer_cutter(cs, z_face, depth, c, up=True):
    """Cutter for a convex hole entering from the face z_face (material below), with a chamfer c."""
    straight = slab(cs, z_face - depth, z_face + 0.5)
    a = slab(cs, z_face - c, z_face - c + 1e-3)
    b = slab(cs.offset(c, JoinType.Round), z_face, z_face + 0.3)
    return straight + Manifold.hull(a + b)

def text_section(text, font, cap_h, cx=0.0, cy=0.0, px_per_mm=60, track=0.0):
    """Raster text with PIL, trace sub-pixel contours, return CrossSection in mm (u right, v up), centred."""
    from PIL import Image, ImageDraw, ImageFont
    from skimage import measure
    size = int(cap_h * px_per_mm / 0.727)        # Inter cap height ≈ 0.727 em
    f = ImageFont.truetype(font, size)
    W = int(size * (len(text) + 2)); H = int(size * 2)
    im = Image.new('L', (W, H), 0)
    d = ImageDraw.Draw(im)
    x = size // 2
    for ch in text:
        d.text((x, size // 2), ch, font=f, fill=255)
        x += d.textlength(ch, font=f) + track * px_per_mm
    a = np.asarray(im, dtype=np.float32) / 255.0
    a = np.pad(a, 2)
    polys = []
    for c in measure.find_contours(a, 0.5):
        c = measure.approximate_polygon(c, tolerance=0.35)
        if len(c) < 4:
            continue
        pts = [(float(p[1]) / px_per_mm, -float(p[0]) / px_per_mm) for p in c[:-1]]
        polys.append(pts)
    cs = CrossSection(polys, FillRule.EvenOdd)
    b = cs.bounds()
    return cs.translate([cx - (b[0] + b[2]) / 2, cy - (b[1] + b[3]) / 2])

def to_three(man):
    mesh = man.to_mesh()
    v = np.asarray(mesh.vert_properties, dtype=np.float64)[:, :3]
    t = np.asarray(mesh.tri_verts, dtype=np.int64)
    v3 = np.stack([v[:, 0], v[:, 2], -v[:, 1]], axis=1)
    return v3, t

def pack(v, t, crease=32, extra=None):
    mn = v.min(axis=0); mx = v.max(axis=0)
    span = np.where(mx - mn > 1e-9, mx - mn, 1.0)
    q = np.round((v - mn) / span * 65535).astype('<u2')
    i32 = len(v) > 65535
    idx = t.astype('<u4' if i32 else '<u2')
    rec = {'v': base64.b64encode(q.tobytes()).decode(), 'i': base64.b64encode(idx.tobytes()).decode(),
           'min': [round(float(x), 6) for x in mn], 'max': [round(float(x), 6) for x in mx],
           'n': int(len(v)), 't': int(len(t)), 'i32': bool(i32), 'crease': crease}
    if extra:
        rec.update(extra)
    return rec

def write_module(name, recs, note):
    path = os.path.join(OUT, name + '.geo.js')
    with open(path, 'w') as fh:
        fh.write('// GENERATED by parts/tools/build_geo.py: do not edit. ' + note + '\n')
        fh.write('export default ' + json.dumps(recs, separators=(',', ':')) + ';\n')
    tris = sum(r['t'] for r in recs.values())
    print(f'{path}: {len(recs)} meshes, {tris} tris, {os.path.getsize(path) / 1024:.0f} KB')

# ----------------------------------------------------------------------------- GT01 cover
FONT = '/usr/share/fonts/opentype/inter/Inter-Bold.otf'

def gt01_cover(marking='GT01'):
    """Translucent cover, switch frame S (origin: body bottom centre; x width, y up, z length, plunger +z).
    Built Z-up in manifold with Y_m = -z."""
    L, W, H = 12.8, 5.8, 6.5
    y_bot, wall, top = 2.0, 0.45, 0.5
    r_top, r_corner = 0.45, 0.7
    outer = rounded_slab(rrect(W, L, r_corner), y_bot - 0.6, H, r_top, 32)
    outer = outer.trim_by_plane([0, 0, 1], y_bot)
    inner = slab(rrect(W - 2 * wall, L - 2 * wall, 0.25), y_bot - 1, H - top)
    cover = outer - inner
    # plunger hole (z = +3.4 -> Y_m = -3.4), chamfered at the top face
    zp = 3.4
    hole = rrect(1.75, 2.3, 0.45, 0, -zp)
    cover = cover - chamfer_cutter(hole, H, top + 0.2, 0.1, up=True)
    # label recess on top, z in [-5.5, 1.3]
    zc, lz, lx, depth = -2.1, 6.8, 3.5, 0.06
    panel = rrect(lx, lz, 0.35, 0, -zc)
    cover = cover - slab(panel, H - depth, H + 0.2)
    if marking:
        # raised marking, reading along +z with tops toward +x (viewer on the -x side)
        cs = text_section(marking, FONT, 1.45, 0, 0, track=0.08)
        # text (u, v) -> (z = u, x = v) -> manifold (Y = -u, X = v): rotate the section by -90°
        cs = cs.rotate(-90).translate([0, -zc])
        cover = cover + slab(cs, H - depth - 0.01, H - 0.012)
        # thin border line inside the recess
        ring = rrect(lx - 0.3, lz - 0.3, 0.22, 0, -zc) - rrect(lx - 0.5, lz - 0.5, 0.15, 0, -zc)
        cover = cover + slab(ring, H - depth - 0.01, H - 0.02)
    # latch windows in both end walls
    for s in (+1, -1):
        win = rrect(2.6, 1.3, 0.2, 0, 3.1)            # (x, y) section, extruded along length
        cut = win.extrude(2.0).translate([0, 0, -1.0])  # along manifold Z → rotate so it runs along Y
        cut = cut.rotate([90, 0, 0]).translate([0, -s * 6.15, 0])
        cover = cover - cut
    return cover

def build_gt01():
    recs = {}
    for mk in ('GT01', ''):
        c = gt01_cover(mk)
        v, t = to_three(c)
        recs['cover' + ('_' + mk if mk else '_plain')] = pack(v, t, crease=30)
    write_module('gt01', recs, 'GT01 cover (switch frame S), representative geometry.')

# ----------------------------------------------------------------------------- M2 pan head, combination recess
def m2_head():
    """ISO 7045-style M2 pan head (dk 4.0, k 1.6) with a Phillips H0 + slot combination recess.
    JS frame: origin at the bearing face centre, head above (+y). Manifold Z = three y."""
    dk, k = 4.0, 1.6
    r = dk / 2
    # profile in (r, z): bearing face with a small under-head fillet into the shank (shank radius 0.98)
    prof = [(0.0, 0.0), (0.98, 0.0)]
    prof += [(0.98 + 0.12 - 0.12 * math.cos(a), -0.12 + 0.12 * math.sin(a) + 0.12) for a in np.linspace(0, math.pi / 2, 5)][1:]
    prof += [(r - 0.08, 0.0), (r, 0.08), (r - 0.02, 0.86)]
    # edge round into a shallow dome (R ≈ 3.2) that peaks at k
    Rd = 3.2
    zc = k - Rd
    a_end = math.asin(min(1, (r - 0.36) / Rd))
    # fillet r 0.36 between the side and the dome
    for a in np.linspace(0, math.pi / 2 - 0.25, 6)[1:]:
        prof.append((r - 0.36 + 0.36 * math.cos(a) - 0.02, 0.86 + 0.36 * math.sin(a) * 0.9))
    for a in np.linspace(a_end, 0, 14):
        prof.append((Rd * math.sin(a), zc + Rd * math.cos(a)))
    prof = [(max(0.0, x), z) for x, z in prof]
    cs = CrossSection([[(x, z) for x, z in prof]])
    head = cs.revolve(96)
    # combination recess: slot across + Phillips cross with a conical centre
    slot = Manifold.cube([dk + 1, 0.52, 0.72]).translate([-(dk + 1) / 2, -0.26, k - 0.66])
    wing = lambda ang: Manifold.hull(
        Manifold.cube([1.9, 0.44, 0.02]).translate([-0.95, -0.22, k + 0.05]) +
        Manifold.cube([0.5, 0.2, 0.02]).translate([-0.25, -0.1, k - 1.0])).rotate([0, 0, ang])
    cone = Manifold.cylinder(1.12, 0.06, 0.62, 48).translate([0, 0, k - 1.08])
    head = head - slot - wing(0) - wing(90) - cone
    return head

def build_fasteners():
    h = m2_head()
    v, t = to_three(h)
    write_module('fasteners', {'m2_head': pack(v, t, crease=34)}, 'M2 pan head with Phillips/slotted combination recess (representative ISO 7045 envelope).')

