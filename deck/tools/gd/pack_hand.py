"""Embed the hand renders (out/hand/*.webp, render_hand.py) in the gd page: -> deck/src/40-gd-05-hand.js (only the gd target
includes 40-gd-*.js, so main.html never carries them). Each frame: its near and far layers as data URIs, and its pose."""
import os, json, base64, glob
HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(HERE, 'out', 'hand')
DST = os.path.join(HERE, '..', '..', 'src', '40-gd-05-hand.js')
import numpy as np
from PIL import Image
def layers(nm, q=86):
    """(re)make a frame's layers from its render and mask: far is the whole hand (the slide clips it by the Sora's profile),
    near only the index and the thumb, drawn over it, so the cut between them never shows (lossy alpha at a cut would)"""
    f, m = os.path.join(OUT, nm + '_full.png'), os.path.join(OUT, nm + '_mask.png')
    if not (os.path.exists(f) and os.path.exists(m)): return
    full = np.asarray(Image.open(f).convert('RGBA')).copy(); mk = np.asarray(Image.open(m).convert('RGBA'))[..., 0] > 127
    near = full.copy(); near[~mk] = 0
    Image.fromarray(near, 'RGBA').save(os.path.join(OUT, nm + '_near.webp'), 'WEBP', quality=q, method=6, alpha_quality=90)
    Image.fromarray(full, 'RGBA').save(os.path.join(OUT, nm + '_far.webp'), 'WEBP', quality=q, method=6, alpha_quality=90)
frames, meta, size = {}, {}, 0
for j in sorted(glob.glob(os.path.join(OUT, '*.json'))):
    nm = os.path.basename(j)[:-5]; m = json.load(open(j)); uri = {}; layers(nm)
    for layer in ('near', 'far'):
        p = os.path.join(OUT, nm + '_' + layer + '.webp')
        if not os.path.exists(p): break
        b = open(p, 'rb').read(); size += len(b); uri[layer] = 'data:image/webp;base64,' + base64.b64encode(b).decode()
    if len(uri) < 2: continue
    frames[nm] = uri; meta[nm] = {'kind': m['kind'], 'k': m['k'], 'ppm': m['ppm'], 'win': m['win'], 'thumb': m['thumb'], 'fingers': m['fingers'], 'ik': m.get('thumb_ik')}
js = ['/* 40-gd-05-hand.js: GENERATED by deck/tools/gd/pack_hand.py from deck/tools/gd/out/hand (render_hand.py, hand3d.py). Do not edit.',
      '   The hand at rest, rendered in Cycles (grey clay, orthographic side view from the thumb\'s side, the nose right), posed joint',
      '   by joint from the model (deck/tools/gd/hand.py). Per frame: near (index and thumb) and far (palm and the other fingers)',
      '   layers (far: the whole hand; near: the index and the thumb, drawn over it), and the pose (hand frame, mm: origin the middle MCP, z along the metacarpals, y dorsal). */',
      'const GD_HANDIMG = (() => {',
      '  const M = ' + json.dumps(meta, separators=(',', ':')) + ';',
      '  const D = ' + json.dumps(frames, separators=(',', ':')) + ';',
      '  const im = s => { const i = new Image(); i.src = s; (window.IMGS = window.IMGS || []).push(i); return i; };',
      '  const out = {}; for (const k in D) out[k] = Object.assign({ near: im(D[k].near), far: im(D[k].far) }, M[k]);',
      '  return out;',
      '})();', '']
open(DST, 'w').write('\n'.join(js))
print('frames', len(frames), 'webp bytes', size, '->', os.path.getsize(DST))
